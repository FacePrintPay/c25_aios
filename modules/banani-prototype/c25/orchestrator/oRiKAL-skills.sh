#!/data/data/com.termux/files/usr/bin/env bash
# oRiKAL SKILLS AGENT - Validator & Executor with File Creation
# Auto-discovers, reads, creates files and routes to all agent.sh scripts

set -euo pipefail

export C25_ROOT="${C25_ROOT:-$HOME/dist-canonical}"
export ORCHESTRATOR_DIR="$C25_ROOT/orchestrator"
export AGENTS_DIR="$C25_ROOT/agents"
export SKILLS_DIR="$C25_ROOT/skills"
export CACHE_DIR="$C25_ROOT/cache"
export RUNTIME_DIR="$C25_ROOT/runtime"

RED='\033[0;31m'; GREEN='\033[0;32m'; CYAN='\033[0;36m'; YELLOW='\033[1;33m'; PURPLE='\033[0;35m'; NC='\033[0m'

log() { echo -e "${PURPLE}[oRiKAL]${NC} $1"; }
ok() { echo -e "${GREEN}[✓]${NC} $1"; }
warn() { echo -e "${YELLOW}[!]${NC} $1"; }
err() { echo -e "${RED}[✗]${NC} $1"; exit 1; }

# Initialize oRiKAL cache
init_cache() {
    mkdir -p "$CACHE_DIR" "$RUNTIME_DIR" "$SKILLS_DIR"
    log "Initialized oRiKAL cache directories"
}

# Read file if exists, create if not
read_or_create_file() {
    local filepath="$1"
    local default_content="${2:-# Auto-generated by oRiKAL\n# $(date)}"
    
    if [[ -f "$filepath" ]]; then
        log "Reading existing file: $filepath"
        cat "$filepath"
        ok "File read successfully"
    else
        warn "File not found, creating: $filepath"
        mkdir -p "$(dirname "$filepath")"
        echo -e "$default_content" > "$filepath"
        ok "File created: $filepath"
    fi
}

# Scan and update all agent.sh files with skills
update_all_agents() {
    log "Scanning for all agent.sh scripts..."
    
    local updated_count=0
    local created_count=0
    
    # Define all 25 planetary agents with their clusters
    declare -A AGENTS=(
        ["Mercury"]="SCAFFOLD"
        ["Venus"]="SCAFFOLD"
        ["Earth"]="SCAFFOLD"
        ["Mars"]="SCAFFOLD"
        ["Jupiter"]="SECURITY"
        ["Saturn"]="SECURITY"
        ["Uranus"]="SECURITY"
        ["Neptune"]="SECURITY"
        ["Pluto"]="RUNTIME"
        ["Ceres"]="RUNTIME"
        ["Eris"]="RUNTIME"
        ["Makemake"]="RUNTIME"
        ["Haumea"]="ORCHESTR"
        ["Sedna"]="ORCHESTR"
        ["Quaoar"]="ORCHESTR"
        ["Orcus"]="ORCHESTR"
        ["Varuna"]="DEPLOY"
        ["Ixion"]="DEPLOY"
        ["Chaos"]="DEPLOY"
        ["Huya"]="DEPLOY"
        ["Salacia"]="MONITOR"
        ["Altjira"]="MONITOR"
        ["Varda"]="MONITOR"
        ["Gonggong"]="MONITOR"
        ["Deimos"]="MONITOR"
    )
    
    for agent_name in "${!AGENTS[@]}"; do
        local cluster="${AGENTS[$agent_name]}"
        local agent_file="$AGENTS_DIR/${agent_name,,}-agent.sh"
        local lowercase_name="${agent_name,,}"
        
        if [[ ! -f "$agent_file" ]]; then
            log "Creating missing agent: $agent_name ($cluster)"
            cat > "$agent_file" << AGENTEOF
#!/data/data/com.termux/files/usr/bin/env bash
# =============================================================================
# $agent_name Agent - $cluster Cluster
# Auto-generated by oRiKAL Validator
# Created: $(date)
# =============================================================================

export AGENT_NAME="$agent_name"
export AGENT_CLUSTER="$cluster"
export AGENT_VERSION="1.0.0"

# Skill registry
declare -a AGENT_SKILLS=()

# Register a skill
register_skill() {
    AGENT_SKILLS+=("\$1")
    echo "[\$AGENT_NAME] Registered skill: \$1"
}

# =============================================================================
# CORE SKILLS
# =============================================================================

skill_file_read() {
    local target="\${1:-}"
    [[ -z "\$target" ]] && { echo "Error: No target file specified"; return 1; }
    [[ -f "\$target" ]] && cat "\$target" || echo "File not found: \$target"
}

skill_file_write() {
    local target="\${1:-}"
    local content="\${2:-}"
    [[ -z "\$target" ]] && { echo "Error: No target file specified"; return 1; }
    mkdir -p "\$(dirname "\$target")"
    echo "\$content" > "\$target"
    echo "[\$AGENT_NAME] Wrote to: \$target"
}

skill_command_exec() {
    local cmd="\${*:-}"
    [[ -z "\$cmd" ]] && { echo "Error: No command specified"; return 1; }
    echo "[\$AGENT_NAME] Executing: \$cmd"
    eval "\$cmd"
}

skill_status_check() {
    echo "[\$AGENT_NAME] Status: ONLINE"
    echo "  Cluster: \$AGENT_CLUSTER"
    echo "  Version: \$AGENT_VERSION"
    echo "  Skills: \${AGENT_SKILLS[*]}"
}

skill_list_directory() {
    local dir="\${1:-.}"
    echo "[\$AGENT_NAME] Listing: \$dir"
    ls -la "\$dir" 2>/dev/null || echo "Directory not found: \$dir"
}

skill_hash_file() {
    local target="\${1:-}"
    [[ -z "\$target" ]] && { echo "Error: No target file specified"; return 1; }
    if command -v sha256sum &>/dev/null; then
        sha256sum "\$target"
    else
        md5sum "\$target" 2>/dev/null || echo "Hash not available"
    fi
}

# =============================================================================
# INITIALIZATION
# =============================================================================

init() {
    log "Initializing \$AGENT_NAME (\$CLUSTER)"
    
    # Register all core skills
    register_skill "file_read"
    register_skill "file_write"
    register_skill "command_exec"
    register_skill "status_check"
    register_skill "list_directory"
    register_skill "hash_file"
    
    ok "\$AGENT_NAME ready with \${#AGENT_SKILLS[@]} skills"
}

# Execute function for external calls
execute() {
    local skill="\${1:-status_check}"
    shift || true
    
    case "\$skill" in
        file_read|read) skill_file_read "\$@" ;;
        file_write|write) skill_file_write "\$@" ;;
        command_exec|exec) skill_command_exec "\$@" ;;
        status_check|status) skill_status_check ;;
        list_directory|ls) skill_list_directory "\$@" ;;
        hash_file|hash) skill_hash_file "\$@" ;;
        *) echo "Unknown skill: \$skill"; return 1 ;;
    esac
}

# Auto-init on source
init

# Run if executed directly
[[ "\${BASH_SOURCE[0]}" == "\${0}" ]] && execute "\$@"
AGENTEOF
            chmod +x "$agent_file"
            ((created_count++))
            ok "Created: $agent_file"
        else
            # Update existing agent with new skills if needed
            if ! grep -q "skill_hash_file" "$agent_file" 2>/dev/null; then
                log "Updating existing agent: $agent_name"
                # Append missing skills
                cat >> "$agent_file" << UPDATEEOF

# oRiKAL Update $(date): Added hash_file skill
skill_hash_file() {
    local target="\${1:-}"
    [[ -z "\$target" ]] && { echo "Error: No target file specified"; return 1; }
    if command -v sha256sum &>/dev/null; then
        sha256sum "\$target"
    else
        md5sum "\$target" 2>/dev/null || echo "Hash not available"
    fi
}

register_skill "hash_file"
UPDATEEOF
                ok "Updated: $agent_file"
            fi
            ((updated_count++))
        fi
    done
    
    echo
    ok "Agent scan complete: $created_count created, $updated_count updated"
}

# Route command to specific agent
route_to_agent() {
    local agent_name="$1"
    local skill="$2"
    shift 2 || true
    local args=("$@")
    
    local agent_file="$AGENTS_DIR/${agent_name,,}-agent.sh"
    
    if [[ ! -f "$agent_file" ]]; then
        err "Agent not found: $agent_name"
    fi
    
    log "Routing to $agent_name: skill=$skill args=${args[*]}"
    source "$agent_file"
    execute "$skill" "${args[@]}"
}

# Generate skills manifest
generate_manifest() {
    log "Generating skills manifest..."
    
    local manifest_file="$SKILLS_DIR/orikal_manifest.json"
    
    cat > "$manifest_file" << MANIFESTEOF
{
  "generator": "oRiKAL",
  "version": "1.0.0",
  "generated": "$(date -Iseconds)",
  "agents_dir": "$AGENTS_DIR",
  "total_agents": 25,
  "clusters": ["SCAFFOLD", "SECURITY", "RUNTIME", "ORCHESTR", "DEPLOY", "MONITOR"],
  "core_skills": [
    "file_read",
    "file_write", 
    "command_exec",
    "status_check",
    "list_directory",
    "hash_file"
  ]
}
MANIFESTEOF
    
    ok "Manifest saved: $manifest_file"
}

# Main execution
main() {
    echo -e "${PURPLE}╔══════════════════════════════════════════════════════════╗${NC}"
    echo -e "${PURPLE}║${NC}         oRiKAL - VALIDATOR & EXECUTOR                  ${PURPLE}║${NC}"
    echo -e "${PURPLE}║${NC}         Quaoar · ORCHESTR Cluster                      ${PURPLE}║${NC}"
    echo -e "${PURPLE}╚══════════════════════════════════════════════════════════╝${NC}"
    echo
    
    init_cache
    
    case "${1:-scan}" in
        scan|update)
            update_all_agents
            generate_manifest
            ;;
        read)
            shift || true
            read_or_create_file "${1:-}" "${2:-}"
            ;;
        route)
            shift || true
            route_to_agent "${1:-}" "${2:-execute}" "${@:3}"
            ;;
        manifest)
            generate_manifest
            ;;
        *)
            echo "Usage: $0 {scan|update|read <file>|route <agent> <skill> [args]|manifest}"
            ;;
    esac
}

main "$@"
